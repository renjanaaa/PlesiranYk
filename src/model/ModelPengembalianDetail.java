
package model;

public class ModelPengembalianDetail {
    private String noDetail;
    private String noPengembalian;
    private String idMobil;
    private int denda;
    private String keterangan;

    public String getNoDetail() {
        return noDetail;
    }

    public void setNoDetail(String noDetail) {
        this.noDetail = noDetail;
    }

    public String getNoPengembalian() {
        return noPengembalian;
    }

    public void setNoPengembalian(String noPengembalian) {
        this.noPengembalian = noPengembalian;
    }

    public String getIdMobil() {
        return idMobil;
    }

    public void setIdMobil(String idMobil) {
        this.idMobil = idMobil;
    }

    public int getDenda() {
        return denda;
    }

    public void setDenda(int denda) {
        this.denda = denda;
    }

    public String getKeterangan() {
        return keterangan;
    }

    public void setKeterangan(String keterangan) {
        this.keterangan = keterangan;
    }
}
